"""Script file discovery for the compose pass.

Responsibility: return ``.rpy`` scripts under ``game_root`` suitable for
scanning, honouring the decompile-generated include set when provided.
"""

from __future__ import annotations

from pathlib import Path

from ..config import GameConfig


def files(
    config: GameConfig,
    include: set[str] | None = None,
) -> list[Path]:
    """Return ``.rpy`` scripts under ``game_root`` suitable for scanning.

    Skips ``cache`` directories and ``composite_images.rpy`` (generated by the
    apply pass).

    When ``include`` is provided (a set of forward-slash paths relative to
    ``game_root``, e.g. from the decompile-generated config.json's
    ``rpy_files``), only scripts whose relative path is in the set are
    returned; the ``archive`` exclusion is then waived so the caller's list is
    honored exactly.  When ``include`` is None, the legacy behavior is kept:
    sweep everything under ``game_root`` except ``archive``/``cache``.
    """
    result: list[Path] = []
    for p in sorted(
        config.game_root.rglob("*.rpy"), key=lambda p: p.as_posix().lower()
    ):
        if p.name == "composite_images.rpy":
            continue
        if include is None:
            if "cache" in p.parts or "archive" in p.parts:
                continue
        else:
            rel = p.relative_to(config.game_root).as_posix()
            if rel not in include:
                continue
        result.append(p)
    return result
