"""Ren'Py script parsing for the compose pass.

Responsibility: statically scan ``.rpy`` scripts and extract structured
representations of ``layeredimage`` blocks, ``screen`` blocks, and ``image``
declarations that reference asset folders.

This module does *not* composite images or write files — it only parses.
All game-specific folder names come from :class:`~converter.compose.config.GameConfig`.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from .config import GameConfig
from .errors import ComposeError
from .models import Layer

# --------------------------------------------------------------------------- #
# Regexes
# --------------------------------------------------------------------------- #

# Matches:  <indent><layeredimage|screen> <name>(...):  at block start
BLOCK_RE = re.compile(
    r"^(\s*)(layeredimage|screen)\s+([\w.]+)(?:\([^\n]*\))?\s*:\s*$"
)

# Matches:  <indent>image <name> = <expression>
IMAGE_RE = re.compile(r"^(\s*)image\s+([\w.]+)\s*=\s*(.*)$")

# Matches:  show|scene <tag> [<transform args>]
SHOW_SCENE_RE = re.compile(r"^\s*(?:show|scene)\s+(?!screen\b)([\w.]+)(?:\s+([^\n#]+))?")

# Matches:  show screen <name>
SHOW_SCREEN_RE = re.compile(r"^\s*show\s+screen\s+([\w.]+)")

# Matches:  default <name> = <value>
DEFAULT_RE = re.compile(
    r"^\s*default\s+([A-Za-z_]\w*)\s*=\s*(True|False|-?\d+(?:\.\d+)?|'[^']*'|\"[^\"]*\")"
)

# Matches:  define <var> = Character("<display>", ... image="<tag>" ...)
CHARACTER_DEF_RE = re.compile(
    r"""^\s*define\s+([A-Za-z_]\w*)\s*=\s*Character\(\s*(['"])(.*?)\2(.*?)\)\s*$"""
)

# Keywords that are not dialogue speakers even when followed by a quoted string.
_NOT_SPEAKER = {
    "add", "show", "scene", "hide", "pause", "jump", "call", "return", "with",
    "as", "to", "parent", "zorder", "if", "elif", "else", "while", "for",
    "in", "not", "and", "or", "True", "False", "None", "screen", "layeredimage",
    "image", "define", "default", "init", "label", "menu", "python",
}

SAY_RE = re.compile(r'^(\s*)([A-Za-z_]\w*)\s+(".*")(\s*#.*)?$')
NARRATOR_RE = re.compile(r'^(\s*)(".*")(\s*#.*)?$')


class ParseError(ComposeError):
    """Raised when a script cannot be parsed."""


def clean(s: str) -> str:
    """Strip comments and surrounding whitespace from a line."""
    return s.split("#", 1)[0].strip()


@dataclass(frozen=True)
class ScriptBlock:
    """A parsed ``layeredimage`` or ``screen`` block."""

    kind: str  # "layeredimage" | "screen"
    name: str
    path: Path
    line: int  # 1-based
    body: list[tuple[int, str]]  # list of (line_number, raw_line)


@dataclass(frozen=True)
class ImageDeclaration:
    """A parsed ``image <name> = <expression>`` declaration."""

    name: str
    script: Path
    line: int  # 1-based
    expression: str
    sources: tuple[str, ...]


@dataclass(frozen=True)
class DialogueLine:
    """A nearby say/narrator statement."""

    speaker: str
    text: str
    line: int


def files(config: GameConfig) -> list[Path]:
    """Return all ``.rpy`` scripts under ``game_root`` suitable for scanning.

    Skips ``archive`` and ``cache`` directories and excludes
    ``composite_images.rpy`` (which is generated by the apply pass).
    """
    return sorted(
        (
            p
            for p in config.game_root.rglob("*.rpy")
            if "cache" not in p.parts
            and "archive" not in p.parts
            and p.name != "composite_images.rpy"
        ),
        key=lambda p: p.as_posix().lower(),
    )


def blocks_from(paths: list[Path], config: GameConfig | None = None) -> list[ScriptBlock]:
    """Parse all ``layeredimage`` and ``screen`` blocks from the given scripts."""
    config = config or _require_config()
    out: list[ScriptBlock] = []
    for path in paths:
        try:
            lines = path.read_text(encoding="utf-8-sig", errors="replace").splitlines()
        except OSError:
            continue
        i = 0
        while i < len(lines):
            m = BLOCK_RE.match(lines[i])
            if not m:
                i += 1
                continue
            indent = len(m.group(1))
            kind = m.group(2)
            name = m.group(3)
            start = i
            i += 1
            body: list[tuple[int, str]] = []
            while i < len(lines):
                raw = lines[i]
                if raw.strip() and len(raw) - len(raw.lstrip()) <= indent:
                    break
                body.append((i + 1, raw))
                i += 1
            out.append(
                ScriptBlock(kind=kind, name=name, path=path, line=start + 1, body=body)
            )
    return out


def parse_layered(block: ScriptBlock, config: GameConfig | None = None) -> list[Layer]:
    """Read source paths and nearby literal attribute/group/condition declarations
    from a ``layeredimage`` block.

    Returns one :class:`Layer` per asset-referencing line, with conditions,
    group, attribute, and offset information populated.
    """
    config = config or _require_config()
    records: list[Layer] = []
    group = ""
    group_indent: int | None = None
    active_attr: str | None = None
    active_default = False
    attr_indent: int | None = None
    condition_stack: list[tuple[int, str]] = []
    chain_counter = 0
    current_chain: tuple[int, int] | None = None  # (indent, chain_id)

    for line_no, raw in block.body:
        text = clean(raw)
        if not text:
            continue
        indent = len(raw) - len(raw.lstrip())
        condition_stack = [(level, cond) for level, cond in condition_stack if level < indent]

        gm = re.match(r"group\s+([\w]+)\s*:", text)
        if group_indent is not None and indent <= group_indent and not gm:
            group = ""
            group_indent = None
            active_attr = None
            active_default = False
            attr_indent = None
        elif attr_indent is not None and indent <= attr_indent:
            active_attr = None
            active_default = False
            attr_indent = None

        if gm:
            group = gm.group(1)
            group_indent = indent
            active_attr = None
            active_default = False
            attr_indent = None
            current_chain = None
            continue

        am = re.match(r"attribute\s+([\w]+)(\s+default)?\s*:", text)
        if am:
            active_attr = am.group(1)
            active_default = bool(am.group(2))
            attr_indent = indent
            current_chain = None
            continue

        cm = re.match(r"(if|elif|else)\s+(.+?)\s*:", text)
        if cm:
            kind, cond = cm.groups()
            if kind == "else":
                cond = "<else>"
            if kind == "if" or current_chain is None or current_chain[0] != indent:
                chain_counter += 1
                current_chain = (indent, chain_counter)
            condition_stack = [(level, value) for level, value in condition_stack if level < indent]
            condition_stack.append((indent, cond))
            continue

        if current_chain is not None and indent <= current_chain[0]:
            current_chain = None

        pm = config.path_regex().search(text)
        if pm:
            offset: tuple[float, float] | None = None
            offset_rel: tuple[float, float] | None = None
            xp = re.search(r"\bxpos\s+([\d.]+)\s*", text)
            yp = re.search(r"\bypos\s+([\d.]+)\s*", text)
            if xp and yp:
                offset = (float(xp.group(1)), float(yp.group(1)))
            xa = re.search(r"\bxalign\s+([\d.]+)\s*", text)
            ya = re.search(r"\byalign\s+([\d.]+)\s*", text)
            if xa and ya:
                offset_rel = (float(xa.group(1)), float(ya.group(1)))
            records.append(
                Layer(
                    source=pm.group(0),
                    line=line_no,
                    group=group,
                    conditions=tuple(c for _, c in condition_stack),
                    attribute=active_attr,
                    default_attribute=active_default,
                    offset=offset,
                    offset_rel=offset_rel,
                    chain_id=str(current_chain[1]) if current_chain else None,
                )
            )
    return records


def parse_screen_stack(
    block: ScriptBlock, definitions: dict[str, tuple[ScriptBlock, list[Layer]]],
    config: GameConfig | None = None,
) -> list[Layer]:
    """Parse the body of a ``screen`` block into a stack of layers.

    Resolves ``add <path>`` and named layeredimage displayables, tracking
    if/elif/else chains so mutually-exclusive alternatives are kept together.
    """
    config = config or _require_config()
    stack: list[Layer] = []
    conditions: list[tuple[int, str]] = []
    chain_counter = 0
    current_chain: tuple[int, int] | None = None

    for line_no, row in block.body:
        text = clean(row)
        if not text:
            continue
        indent = len(row) - len(row.lstrip())
        conditions = [(level, cond) for level, cond in conditions if level < indent]

        cm = re.match(r"(?:if|elif)\s+(.+?)\s*:", text)
        if cm:
            if current_chain is None or current_chain[0] != indent:
                chain_counter += 1
                current_chain = (indent, chain_counter)
            conditions = [(level, cond) for level, cond in conditions if level < indent]
            conditions.append((indent, cm.group(1)))
            continue

        if text == "else:":
            if current_chain is None or current_chain[0] != indent:
                chain_counter += 1
                current_chain = (indent, chain_counter)
            conditions = [(level, cond) for level, cond in conditions if level < indent]
            conditions.append((indent, "<else>"))
            continue

        if current_chain is not None and indent <= current_chain[0]:
            current_chain = None

        chain_id = f"screen:{current_chain[1]}" if current_chain else None

        quoted = re.match(r'add\s+([\'"])(.+?)\1', text)
        if quoted and config.path_regex().search(quoted.group(2)):
            offset, offset_rel = _parse_position_from_transforms(
                text[quoted.end() :].strip()
            )
            stack.append(
                Layer(
                    source=quoted.group(2),
                    line=line_no,
                    conditions=tuple(c for _, c in conditions),
                    role="screen_add",
                    offset=offset,
                    offset_rel=offset_rel,
                    chain_id=chain_id,
                )
            )
        elif quoted and quoted.group(2) in definitions:
            tag = quoted.group(2)
            _extend_with_definition(
                stack, tag, definitions[tag][1], conditions, chain_id
            )
        elif quoted and quoted.group(2).lower().startswith(
            tuple(f"{n}/" for n in config.categories.values())
        ):
            offset, offset_rel = _parse_position_from_transforms(
                text[quoted.end() :].strip()
            )
            stack.append(
                Layer(
                    source=quoted.group(2),
                    line=line_no,
                    conditions=tuple(c for _, c in conditions),
                    role="screen_add",
                    offset=offset,
                    offset_rel=offset_rel,
                    chain_id=chain_id,
                )
            )
        else:
            named = re.match(r"add\s+([\w.]+)", text)
            if named and named.group(1) in definitions:
                tag = named.group(1)
                _extend_with_definition(
                    stack, tag, definitions[tag][1], conditions, chain_id
                )
    return stack


def _extend_with_definition(
    stack: list[Layer],
    tag: str,
    definition_layers: list[Layer],
    conditions: list[tuple[int, str]],
    chain_id: str | None,
) -> None:
    """Append layers expanded from a named layeredimage definition."""
    for layer in definition_layers:
        new_chain_id = None
        if layer.chain_id is not None:
            new_chain_id = f"def:{tag}:{layer.chain_id}"
        elif chain_id is not None:
            new_chain_id = chain_id
        stack.append(
            layer.replace(
                conditions=tuple(c for _, c in conditions) + tuple(layer.conditions),
                via_image_tag=tag,
                chain_id=new_chain_id,
            )
        )


def parse_image_declarations(
    script_files: list[Path], config: GameConfig | None = None,
) -> dict[str, ImageDeclaration]:
    """Index all ``image`` declarations that reference asset paths."""
    config = config or _require_config()
    declarations: dict[str, ImageDeclaration] = {}
    for path in script_files:
        source_lines = path.read_text(encoding="utf-8-sig", errors="replace").splitlines()
        i = 0
        while i < len(source_lines):
            raw = source_lines[i]
            im = IMAGE_RE.match(clean(raw))
            if im:
                _, name, expression = im.groups()
                declaration_indent = len(raw) - len(raw.lstrip())
                expr_lines = [expression]
                j = i + 1
                while j < len(source_lines):
                    following = source_lines[j]
                    if following.strip() and len(following) - len(following.lstrip()) <= declaration_indent:
                        break
                    expr_lines.append(clean(following))
                    j += 1
                expression = "\n".join(expr_lines)
                sources = tuple(
                    m.group(0) for m in config.path_regex().finditer(expression)
                )
                if sources and name not in declarations:
                    declarations[name] = ImageDeclaration(
                        name=name,
                        script=path,
                        line=i + 1,
                        expression=expression,
                        sources=sources,
                    )
                i = j
            else:
                i += 1
    return declarations


def find_nearby_dialog(
    path: Path, line_number: int, lookback: int = 60, lines: list[str] | None = None,
) -> list[DialogueLine]:
    """Find dialog/narration statements near a given line in a script.

    Scans backwards from ``line_number`` looking for Ren'Py ``say`` statements
    and narrator lines.  Returns them ordered from most recent to oldest.

    If ``lines`` is supplied (e.g. from a single-pass script index) the file is
    not re-read from disk (Optimization #1).
    """
    if lines is None:
        try:
            lines = path.read_text(encoding="utf-8-sig", errors="replace").splitlines()
        except OSError:
            return []

    start = max(0, line_number - 1)
    end = max(0, start - lookback)
    dialog: list[DialogueLine] = []
    for i in range(start - 1, end - 1, -1):
        raw = lines[i]
        text = raw.strip()
        if not text or text.startswith("#"):
            continue

        m = SAY_RE.match(raw)
        if m:
            speaker = m.group(2)
            if speaker in _NOT_SPEAKER:
                continue
            dialog_text = m.group(3)
            if _looks_like_asset_path(dialog_text):
                continue
            dialog.append(DialogueLine(speaker=speaker, text=dialog_text, line=i + 1))
            continue

        m = NARRATOR_RE.match(raw)
        if m:
            dialog_text = m.group(1)
            if _looks_like_asset_path(dialog_text):
                continue
            dialog.append(DialogueLine(speaker="narrator", text=dialog_text, line=i + 1))

    return dialog


def _looks_like_asset_path(text: str) -> bool:
    t = text.strip().strip('"').strip("'")
    return "/" in t or "\\" in t or t.lower().endswith(
        (".png", ".jpg", ".jpeg", ".webp", ".bmp")
    )


def _parse_position_from_transforms(transforms: str) -> tuple[tuple[float, float] | None, tuple[float, float] | None]:
    """Extract xpos/ypos or xalign/yalign from transform text."""
    offset: tuple[float, float] | None = None
    offset_rel: tuple[float, float] | None = None
    xp = re.search(r"\bxpos\s+([\d.]+)\s*", transforms)
    yp = re.search(r"\bypos\s+([\d.]+)\s*", transforms)
    if xp and yp:
        offset = (float(xp.group(1)), float(yp.group(1)))
    xa = re.search(r"\bxalign\s+([\d.]+)\s*", transforms)
    ya = re.search(r"\byalign\s+([\d.]+)\s*", transforms)
    if xa and ya:
        offset_rel = (float(xa.group(1)), float(ya.group(1)))
    return offset, offset_rel


# --------------------------------------------------------------------------- #
# Single-pass script indexer (Optimization #1)
# --------------------------------------------------------------------------- #

_IMAGE_TAG_RE = re.compile(r"""image\s*=\s*(['"])(.*?)\1""")


@dataclass(frozen=True)
class ScriptUsage:
    """A usage of a tag/declaration/screen found in a script during indexing."""

    script: Path
    line: int
    statement: str
    tag: str
    kind: str  # "show_scene" or "show_screen"


@dataclass(frozen=True)
class FileIndex:
    """Everything extracted from a single .rpy file in one read."""

    path: Path
    lines: tuple[str, ...]  # full file text, kept so downstream passes never re-read
    blocks: list[ScriptBlock]
    image_declarations: dict[str, ImageDeclaration]
    defaults: dict[str, object]
    usages: list[ScriptUsage]
    character_defs: list[tuple[str, str, str]]  # (speaker, display_name, image_tag)


@dataclass(frozen=True)
class ScriptIndex:
    """Single-pass index of all .rpy scripts — each file read exactly once."""

    files: list[Path]
    per_file: dict[Path, FileIndex]
    layeredimage_defs: dict[str, tuple[ScriptBlock, list[Layer]]]
    screens: dict[str, ScriptBlock]
    image_decls: dict[str, ImageDeclaration]
    all_defaults: dict[str, object]


def index_scripts(config: GameConfig) -> ScriptIndex:
    """Read every .rpy file once and build a complete in-memory index.

    Replaces the 6–8 redundant full-file reads that the old pipeline performed
    (blocks, declarations, defaults, three usage scans, two character-associator
    walks).  Each file is opened and read exactly once here; every downstream
    pass consumes the in-memory index instead of re-reading from disk.
    """
    script_files = files(config)
    per_file: dict[Path, FileIndex] = {}
    layeredimage_defs: dict[str, tuple[ScriptBlock, list[Layer]]] = {}
    screens: dict[str, ScriptBlock] = {}
    image_decls: dict[str, ImageDeclaration] = {}
    all_defaults: dict[str, object] = dict(config.game_defaults)

    for path in script_files:
        try:
            lines = path.read_text(encoding="utf-8-sig", errors="replace").splitlines()
        except OSError:
            continue

        blocks = _parse_blocks_in_lines(lines, path)
        decls = _parse_declarations_in_lines(lines, path, config)
        defaults = _parse_defaults_in_lines(lines)
        usages = _find_all_usages_in_lines(lines, path)
        char_defs = _parse_character_defs_in_lines(lines, path)

        per_file[path] = FileIndex(
            path=path,
            lines=tuple(lines),
            blocks=blocks,
            image_declarations=decls,
            defaults=defaults,
            usages=usages,
            character_defs=char_defs,
        )

        for block in blocks:
            if block.kind == "layeredimage" and block.name not in layeredimage_defs:
                layeredimage_defs[block.name] = (block, parse_layered(block, config))
            elif block.kind == "screen" and block.name not in screens:
                screens[block.name] = block

        for name, decl in decls.items():
            if name not in image_decls:
                image_decls[name] = decl

        for key, value in defaults.items():
            if key not in all_defaults:
                all_defaults[key] = value

    return ScriptIndex(
        files=script_files,
        per_file=per_file,
        layeredimage_defs=layeredimage_defs,
        screens=screens,
        image_decls=image_decls,
        all_defaults=all_defaults,
    )


# --- Single-file parsing helpers (operate on already-read lines) ---


def _parse_blocks_in_lines(lines: list[str], path: Path) -> list[ScriptBlock]:
    """Parse layeredimage/screen blocks from already-read lines."""
    out: list[ScriptBlock] = []
    i = 0
    while i < len(lines):
        m = BLOCK_RE.match(lines[i])
        if not m:
            i += 1
            continue
        indent = len(m.group(1))
        kind = m.group(2)
        name = m.group(3)
        start = i
        i += 1
        body: list[tuple[int, str]] = []
        while i < len(lines):
            raw = lines[i]
            if raw.strip() and len(raw) - len(raw.lstrip()) <= indent:
                break
            body.append((i + 1, raw))
            i += 1
        out.append(
            ScriptBlock(kind=kind, name=name, path=path, line=start + 1, body=body)
        )
    return out


def _parse_declarations_in_lines(
    lines: list[str], path: Path, config: GameConfig
) -> dict[str, ImageDeclaration]:
    """Parse image declarations from already-read lines."""
    declarations: dict[str, ImageDeclaration] = {}
    i = 0
    while i < len(lines):
        raw = lines[i]
        im = IMAGE_RE.match(clean(raw))
        if im:
            _, name, expression = im.groups()
            declaration_indent = len(raw) - len(raw.lstrip())
            expr_lines = [expression]
            j = i + 1
            while j < len(lines):
                following = lines[j]
                if following.strip() and len(following) - len(following.lstrip()) <= declaration_indent:
                    break
                expr_lines.append(clean(following))
                j += 1
            expression = "\n".join(expr_lines)
            sources = tuple(m.group(0) for m in config.path_regex().finditer(expression))
            if sources and name not in declarations:
                declarations[name] = ImageDeclaration(
                    name=name,
                    script=path,
                    line=i + 1,
                    expression=expression,
                    sources=sources,
                )
            i = j
        else:
            i += 1
    return declarations


def _parse_literal(value: str) -> bool | int | float | str | None:
    """Parse a Ren'Py default literal into a Python value, or None."""
    value = value.strip()
    if value == "True":
        return True
    if value == "False":
        return False
    if re.fullmatch(r"-?\d+\.\d+", value):
        return float(value)
    if re.fullmatch(r"-?\d+", value):
        return int(value)
    if value[:1] in ("'", '"') and value[-1:] == value[:1]:
        return value[1:-1]
    return None


def _parse_defaults_in_lines(lines: list[str]) -> dict[str, object]:
    """Parse default variable assignments from already-read lines."""
    defaults: dict[str, object] = {}
    for raw in lines:
        dm = re.match(
            r"^\s*default\s+([A-Za-z_]\w*)\s*=\s*(True|False|-?\d+(?:\.\d+)?|'[^']*'|\"[^\"]*\")",
            raw.split("#", 1)[0].strip(),
        )
        if dm:
            key, value = dm.groups()
            parsed = _parse_literal(value)
            if parsed is not None:
                defaults[key] = parsed
    return defaults


def _find_all_usages_in_lines(lines: list[str], path: Path) -> list[ScriptUsage]:
    """Find all show/scene/show-screen usage lines in already-read lines."""
    usages: list[ScriptUsage] = []
    for no, raw in enumerate(lines, 1):
        text = clean(raw)
        m = SHOW_SCENE_RE.match(text)
        if m:
            usages.append(
                ScriptUsage(
                    script=path, line=no, statement=text,
                    tag=m.group(1), kind="show_scene",
                )
            )
            continue
        sm = SHOW_SCREEN_RE.match(text)
        if sm:
            usages.append(
                ScriptUsage(
                    script=path, line=no, statement=text,
                    tag=sm.group(1), kind="show_screen",
                )
            )
    return usages


def _parse_character_defs_in_lines(lines: list[str], path: Path) -> list[tuple[str, str, str]]:
    """Extract (speaker, display_name, image_tag) from Character() definitions in lines."""
    defs: list[tuple[str, str, str]] = []
    for raw in lines:
        match = CHARACTER_DEF_RE.match(raw.split("#", 1)[0].strip())
        if not match:
            continue
        speaker, _, display_name, tail = match.groups()
        image_match = _IMAGE_TAG_RE.search(tail)
        image_tag = image_match.group(2).lower() if image_match else ""
        defs.append((speaker, display_name, image_tag))
    return defs


def _require_config() -> GameConfig:
    """Called when no config was explicitly passed — should not happen in refactored code."""
    raise ComposeError(
        "compose config not initialized; pass a GameConfig explicitly"
    )
