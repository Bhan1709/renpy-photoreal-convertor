"""Helper to add exclusion patterns to src/converter/config.json and sync them across decompile re-runs.

Adding a pattern::

    python src/converter/decompile/update_exclusions.py archive/ tl/None/

Syncing (re-run decompile while preserving exclusions)::

    python src/converter/decompile/update_exclusions.py --sync

Reads ``src/converter/config.json`` (generated by the decompile flow), appends
each given pattern to ``exclusion.patterns`` (skipping duplicates), and writes
the file back.  With ``--sync``, it first re-runs the decompile flow to
regenerate ``config.json``, then re-applies the exclusion patterns that were
saved in the previous config so they are not lost when decompile is re-run.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

CONFIG_PATH = Path("src/converter/config.json")
DECOMPILE_SCRIPT = Path("src/converter/decompile/decompile.py")


def _load_config() -> dict:
    if not CONFIG_PATH.exists():
        return {}
    try:
        return json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}


def _save_config(config: dict) -> None:
    CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    CONFIG_PATH.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")


def _get_exclusions(config: dict) -> list[str]:
    return config.get("exclusion", {}).get("patterns", []) or []


def add_exclusions(patterns: list[str]) -> tuple[list[str], list[str]]:
    r"""Add ``patterns`` to ``exclusion.patterns`` in the config.

    Returns ``(added, existing)`` where ``added`` are the newly inserted
    patterns and ``existing`` is the full list after the update.
    """
    config = _load_config()
    if not config:
        print(f"Config not found: {CONFIG_PATH}")
        print("Run 'mise run decompile' first to generate it.")
        sys.exit(1)

    exclusion = config.setdefault(
        "exclusion",
        {"patterns": [], "note": "Glob/substring patterns to exclude from downstream processing"},
    )
    existing: list[str] = exclusion.setdefault("patterns", [])

    added: list[str] = []
    for pattern in patterns:
        if pattern and pattern not in existing:
            existing.append(pattern)
            added.append(pattern)

    _save_config(config)
    return added, existing


def sync_exclusions(new_patterns: list[str] | None = None) -> list[str]:
    r"""Re-run decompile and re-apply saved exclusion patterns.

    Reads the exclusion patterns currently in ``config.json``, re-runs the
    decompile flow (which regenerates ``config.json`` with empty exclusions),
    then re-applies the saved patterns plus any ``new_patterns``.

    Returns the final list of exclusion patterns.
    """
    current = _load_config()
    saved = _get_exclusions(current)

    # Re-run the decompile flow to regenerate config.json.
    result = subprocess.run(
        [sys.executable, str(DECOMPILE_SCRIPT)],
        capture_output=True,
        text=True,
    )
    if result.stdout:
        print(result.stdout, end="")
    if result.stderr:
        print(result.stderr, end="", file=sys.stderr)
    if result.returncode != 0:
        print(f"Decompile failed with exit code {result.returncode}", file=sys.stderr)
        sys.exit(result.returncode)

    # Re-apply saved exclusions (plus any new ones) to the regenerated config.
    config = _load_config()
    exclusion = config.setdefault(
        "exclusion",
        {"patterns": [], "note": "Glob/substring patterns to exclude from downstream processing"},
    )
    existing: list[str] = exclusion.setdefault("patterns", [])

    to_apply = list(saved)
    if new_patterns:
        for pattern in new_patterns:
            if pattern and pattern not in to_apply:
                to_apply.append(pattern)

    for pattern in to_apply:
        if pattern and pattern not in existing:
            existing.append(pattern)

    _save_config(config)
    return existing


def main(argv: list[str] | None = None) -> int:
    patterns = argv if argv is not None else sys.argv[1:]

    if "--sync" in patterns:
        new_patterns = [p for p in patterns if p != "--sync"]
        final = sync_exclusions(new_patterns)
        print(f"Synced {len(final)} exclusion pattern(s): {final}")
        print(f"Config: {CONFIG_PATH}")
        return 0

    if not patterns:
        print("Usage:")
        print("  python src/converter/decompile/update_exclusions.py <pattern> [pattern...]")
        print('      Add exclusion pattern(s) to config.json')
        print("  python src/converter/decompile/update_exclusions.py --sync [<pattern>...]")
        print("      Re-run decompile and re-apply saved exclusion pattern(s)")
        print('Example: python src/converter/decompile/update_exclusions.py archive/ tl/None/')
        return 1

    added, existing = add_exclusions(patterns)
    print(f"Added {len(added)} exclusion pattern(s): {added}")
    print(f"Total exclusions: {len(existing)}")
    print(f"Config: {CONFIG_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
